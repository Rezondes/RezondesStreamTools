// Writes the Rust mirror of the fine-tuning tables of the themes: src/themes/<id>/tuning.ts exports TUNING_FIELDS (the
// fields, in schema order) and TUNING_GROUPS (the scenes of their groups); this script turns them into
// server-rs/crates/rst-domain/src/themes/tuning/<id>.rs with the same builder calls, so the two sides stay equal
// without writing every field twice. The fixture test (same_as_typescript) compares the result field by field.
//   node scripts/tuning.ts        rewrite the Rust files
// tuning.check.ts fails when a Rust file no longer matches its table.
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import type { SceneName, SettingField } from "../src/core/theme.ts";

export const TUNING_DIR = join("server-rs", "crates", "rst-domain", "src", "themes", "tuning");
export const THEME_IDS = ["standard", "matrix", "urlaub", "plantage", "koth", "bears", "chaos", "dachdecker", "kebab", "dogs"] as const;

export type TuningModule = { TUNING_FIELDS: readonly SettingField[]; TUNING_GROUPS: Readonly<Record<string, readonly SceneName[]>> };

const UNITS = { px: "Px", ms: "Ms", s: "S", "%": "Percent" } as const;
const quote = (text: string) => JSON.stringify(text);
// A Rust f64 literal: 12 becomes 12.0, 0.5 stays
const float = (value: number) => (Number.isInteger(value) ? `${value}.0` : String(value));
const option = (value: string | undefined) => (value === undefined ? "None" : `Some(${value})`);
const scene = (name: SceneName) => name.charAt(0).toUpperCase() + name.slice(1);

// The builder call of one field (template: the builders in src/core/fields.ts and settings/field.rs)
export function rustField(field: SettingField): string {
  const head = `${quote(field.key)}, ${quote(field.label)}, ${quote(field.group)}`;
  let call: string;
  switch (field.type) {
    case "color": call = `color(${head}, ${quote(field.default)})`; break;
    case "number": call = `number(${head}, ${float(field.default)}, ${float(field.min)}, ${float(field.max)}, ${option(field.unit && `Unit::${UNITS[field.unit]}`)}, ${option(field.step === undefined ? undefined : float(field.step))})`; break;
    case "boolean": call = `flag(${head}, ${field.default})`; break;
    case "text": call = `text(${head}, ${quote(field.default)}, ${option(field.maxLength === undefined ? undefined : String(field.maxLength))})`; break;
    case "select": call = `choice(${head}, ${quote(field.default)}, &[${field.options.map(quote).join(", ")}])`; break;
    case "font": call = `font(${head}, ${quote(field.default)}, &[${field.options.map(quote).join(", ")}])`; break;
    default: throw new Error(`tuning field ${field.key}: type ${field.type} has no generated builder`);
  }
  if (field.inherit !== undefined) call = `inherits(${call}, ${quote(field.inherit)})`;
  if (field.scene !== undefined) call = `in_scene(SceneName::${scene(field.scene)}, ${call})`;
  return call;
}

export function rustText(id: string, module: TuningModule): string {
  const used = ["SettingField", ...new Set(module.TUNING_FIELDS.flatMap(field => {
    const builder = { color: "color", number: "number", boolean: "flag", text: "text", select: "choice", font: "font" }[field.type as string] ?? field.type;
    return [builder, ...(field.inherit === undefined ? [] : ["inherits"]), ...(field.scene === undefined ? [] : ["in_scene"]), ...(field.type === "number" && field.unit ? ["Unit"] : [])];
  }))].sort((first, second) => (first === "SettingField" ? -1 : second === "SettingField" ? 1 : first.localeCompare(second)));
  const fields = module.TUNING_FIELDS.map(field => `        ${rustField(field)},`).join("\n");
  const groups = Object.entries(module.TUNING_GROUPS).map(([group, scenes]) => `        (${quote(group)}, vec![${scenes.map(name => `SceneName::${scene(name)}`).join(", ")}]),`).join("\n");
  return `//! Fine-tuning fields of the theme ${id}, generated by \`node scripts/tuning.ts\` from \`src/themes/${id}/tuning.ts\`.
//! Do not edit: change the table there and run the script again.

#![allow(clippy::too_many_lines, reason = "schema data: one line per field")]

use crate::settings::field::{${used.join(", ")}};
use crate::themes::schema::SceneName;

/// The fields in schema order
#[must_use]
#[rustfmt::skip]
pub fn fields() -> Vec<SettingField> {
    vec![
${fields}
    ]
}

/// The scenes of the fine-tuning groups
#[must_use]
#[rustfmt::skip]
pub fn group_scenes() -> Vec<(&'static str, Vec<SceneName>)> {
    vec![
${groups}
    ]
}
`;
}

export const modText = (ids: readonly string[]) =>
  `//! Fine-tuning fields per theme, generated by \`node scripts/tuning.ts\` from \`src/themes/<id>/tuning.ts\`.\n\n${ids.map(id => `pub mod ${id};`).join("\n")}\n`;

// The themes that have a table, with their module
export async function tuningModules(): Promise<{ id: string; module: TuningModule }[]> {
  const found = THEME_IDS.filter(id => existsSync(join("src", "themes", id, "tuning.ts")));
  return Promise.all(found.map(async id => ({ id, module: (await import(pathToFileURL(join("src", "themes", id, "tuning.ts")).href)) as TuningModule })));
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const modules = await tuningModules();
  mkdirSync(TUNING_DIR, { recursive: true });
  for (const { id, module } of modules) writeFileSync(join(TUNING_DIR, `${id}.rs`), rustText(id, module));
  writeFileSync(join(TUNING_DIR, "mod.rs"), modText(modules.map(entry => entry.id)));
  console.log(`tuning: ${modules.map(entry => entry.id).join(", ") || "no tables"}`);
}
